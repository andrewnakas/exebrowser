#!/usr/bin/env node
// Generates public/dosbox-snap/wdosbox.js — the snapshot-capable DOSBox glue.
//
// Why a patched copy exists at all: taking a real savestate needs the
// Emscripten `Asyncify` object (where the unwound C stack pointer lives) and
// `wasmMemory` (to grow and overwrite the heap). Both are closure-local inside
// wdosbox.js; nothing reaches them from the page. Four assignments fix that.
//
// Why it's generated rather than committed as a hand-edit: the patch has to
// survive a js-dos upgrade. Re-run this after replacing public/dosbox/, and
// the check below fails loudly if upstream moved the code out from under it
// rather than producing a runtime that looks fine and can't snapshot.
//
//   node scripts/make-snap-runtime.mjs
//
// The wasm is copied unchanged alongside it. It would be nicer to point at
// /dosbox/wdosbox.wasm and reuse the cache entry visitors already have, but
// js-dos fetches the wasm itself from `pathPrefix` rather than letting the
// Emscripten glue locate it, so the file has to sit next to the JS. 1.4 MB of
// duplication that only ships because the spike is small and flag-gated.
//
// Nothing loads this unless ?snapshot=1 is set AND the slug is on
// dos-snapshot.js's allowlist. /dosbox/ is untouched: with the flag off, every
// visitor gets byte-identical files and the same cache entries as before.

import { readFileSync, writeFileSync, mkdirSync, copyFileSync, statSync } from "node:fs";
import { resolve } from "node:path";

const ROOT = resolve(process.cwd(), "public");
const SRC = resolve(ROOT, "dosbox", "wdosbox.js");
const OUT_DIR = resolve(ROOT, "dosbox-snap");
const OUT = resolve(OUT_DIR, "wdosbox.js");

const HEADER =
  "/* GENERATED by scripts/make-snap-runtime.mjs from /dosbox/wdosbox.js." +
  " Do not edit. Re-run after any js-dos upgrade. */\n";

let src = readFileSync(SRC, "utf8");

// ── patch 1: expose the internals a snapshot needs ────────────────────────
//
// updateMemoryViews is the right seam: it already runs at startup and again
// after every heap growth, so the exported references can never go stale
// (HEAPU8 is detached and rebuilt on growth, and a snapshot restore grows the
// heap deliberately).
const VIEWS = "function updateMemoryViews(){var b=wasmMemory.buffer;";
if (!src.includes(VIEWS)) {
  throw new Error(
    "updateMemoryViews() no longer looks the way this patch expects — " +
    "js-dos changed shape. Re-derive the patch before shipping the spike."
  );
}
src = src.replace(
  VIEWS,
  VIEWS +
    'Module["Asyncify"]=Asyncify;' +
    'Module["wasmMemory"]=wasmMemory;' +
    'Module["wasmExports"]=wasmExports;' +
    'Module["updateMemoryViews"]=updateMemoryViews;'
);

// ── patch 2: let the restored emulator see continuous time ────────────────
//
// This one is not an optimisation, it is the difference between working and
// not. DOSBox keeps its timing base in the heap, so a snapshot restored ten
// minutes later comes back convinced it is ten minutes behind and burns
// itself down in a catch-up loop: every sleep goes non-skippable and not a
// single frame is rendered. Measured directly — a snapshot restored with no
// wall-clock gap resumes perfectly, the same snapshot restored after a reload
// renders nothing.
//
// So the clock the wasm sees is shifted by an offset the page controls. On
// restore we set the skew to the gap that elapsed, and DOSBox goes on
// believing no time passed at all.
// Two offsets, not one: performance.now() restarts at zero on every
// navigation while Date.now() keeps counting, so the correction each needs
// after a reload is completely different.
const CLOCKS = [
  ["var _emscripten_get_now=()=>performance.now();",
   "var _emscripten_get_now=()=>performance.now()-(Module.__perfSkew||0);"],
  ["var _emscripten_date_now=()=>Date.now();",
   "var _emscripten_date_now=()=>Date.now()-(Module.__dateSkew||0);"],
];
for (const [from, to] of CLOCKS) {
  if (!src.includes(from)) {
    throw new Error("clock shim target not found: " + from + " — re-derive patch 2.");
  }
  src = src.replace(from, to);
}

// Guard against patching a copy of itself.
if (src.includes(HEADER.trim())) throw new Error("source is already a generated copy");

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(OUT, HEADER + src);
copyFileSync(resolve(ROOT, "dosbox", "wdosbox.wasm"), resolve(OUT_DIR, "wdosbox.wasm"));

// Prove the patches are in the output rather than trusting the replaces.
const written = readFileSync(OUT, "utf8");
for (const needle of ['Module["Asyncify"]=Asyncify', "performance.now()-(Module.__perfSkew||0)"]) {
  if (!written.includes(needle)) throw new Error("patch missing from output: " + needle);
}

const wasmKB = statSync(resolve(OUT_DIR, "wdosbox.wasm")).size / 1024;
console.log(`wrote ${OUT} (${(written.length / 1024).toFixed(0)} KB) + wdosbox.wasm (${wasmKB.toFixed(0)} KB)`);
